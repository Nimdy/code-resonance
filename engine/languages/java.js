'use strict';
// Java adapter: a dependency-free scanner over the shared lexer (engine/languages/scan.js; text blocks and char
// literals included).
//
// Recognised: classes, enums and records (class; record components are properties), interfaces and annotation types
// (interface), methods and constructors owned by their type (nested types are owned by the enclosing one), abstract
// and interface methods, fields (property; `int a, b;` gives both), and HTTP handlers with a literal path: Spring
// @GetMapping/@PostMapping/.../@RequestMapping (a class-level @RequestMapping is the prefix), Micronaut @Get("/x")
// (with @Controller("/prefix")) and JAX-RS @GET + @Path.
// Imports: a package is a folder by convention, so `import com.acme.foo.Bar` is <root>/com/acme/foo/Bar.java where
// <root> is this file's folder minus its own package (src/main/java for com.acme.app); a nested or static member
// falls back to its outer class's file, `import com.acme.foo.*` to a file of that folder, and src/main/kotlin is tried
// beside src/main/java. When the folder does not spell the package, imports stay unresolved.
// Not recognised: enum constants, local and anonymous classes, lambdas, members generated by annotation processors
// (Lombok), and routes whose path is a constant rather than a literal.
const scan=require('./scan');
const DIALECT={chars:'c',triple:true};
const MODIFIERS=/^(?:(?:public|protected|private|static|final|abstract|native|synchronized|transient|volatile|strictfp|default|sealed|non-sealed)\s+)*/;
const KEYWORDS=new Set(['if','for','while','switch','catch','synchronized','return','new','throw','else','do','try','assert','super','this','case']);
const SPRING=/^(Get|Post|Put|Delete|Patch|Request)Mapping$/,MICRONAUT=/^(Get|Post|Put|Delete|Patch|Head|Options)$/,JAXRS=/^(GET|POST|PUT|DELETE|PATCH|HEAD|OPTIONS)$/;
const paren=(src,a)=>{const p=src.code.indexOf('(',a.start);return p>=0&&p<a.end?p:-1;};
// The route prefix a type declares (Spring @RequestMapping, JAX-RS @Path, Micronaut @Controller).
function routePrefix(src,list){
  for(const a of list){const n=a.name.split('.').pop();if(n==='RequestMapping'||n==='Path'||n==='Controller'){const p=paren(src,a);const v=p<0?null:scan.pathArg(src,p,src.match[p]);if(v!==null)return v;}}
  return '';
}
// A handler's route from its annotations, joined to the type's prefix; null when it is not a handler.
function routeOf(src,list,prefix){
  const path=list.find(a=>a.name.split('.').pop()==='Path');
  for(const a of list){
    const n=a.name.split('.').pop(),p=paren(src,a);let m;
    if((m=SPRING.exec(n))){
      const v=p<0?'':scan.pathArg(src,p,src.match[p]);if(v===null)return null;
      let method=m[1].toUpperCase();
      if(method==='REQUEST'){const ms=p<0?[]:[...src.code.slice(p,src.match[p]).matchAll(/RequestMethod\.([A-Z]+)/g)].map(x=>x[1]);method=ms.length===1?ms[0]:'ROUTE';}
      return scan.routeName(method,scan.joinRoute(prefix,v));
    }
    if((m=MICRONAUT.exec(n))&&p>=0){const v=scan.pathArg(src,p,src.match[p],['value','uri']);if(v!==null)return scan.routeName(m[1].toUpperCase(),scan.joinRoute(prefix,v));}
    if((m=JAXRS.exec(n))&&p<0){const q=path?paren(src,path):-1;const v=q<0?'':scan.pathArg(src,q,src.match[q]);return scan.routeName(m[1],scan.joinRoute(prefix,v||''));}
  }
  return null;
}
// Imports by folder convention (shared with Kotlin): candidates are class files, `dir` the package folder.
function jvmImport(spec,name,{wildcard,member,base,kotlin}){
  const imp={spec:spec.slice(0,180),target:null};if(!base)return imp;
  const segs=name.split('.').filter(Boolean);
  const roots=[base];if(/(?:^|\/)java$/.test(base.root))roots.push({...base,root:base.root.replace(/java$/,'kotlin')});else if(/(?:^|\/)kotlin$/.test(base.root))roots.push({...base,root:base.root.replace(/kotlin$/,'java')});
  const candidate=[],dir=[];
  for(const r of roots){
    const at=k=>scan.packageDir(r,segs.slice(0,k));
    if(wildcard){const d=at(segs.length);if(d!==null){if(member)candidate.push(d);else dir.push(d);}continue;}
    // The class's file, then its outer class's (a nested class, or the class of a static member).
    for(let k=segs.length-(member?1:0);k>=Math.max(1,segs.length-1-(member?1:0));k--){const c=at(k);if(c)candidate.push(c);}
    if(kotlin){const d=at(segs.length-1);if(d!==null)dir.push(d);}
  }
  return {...imp,...(candidate.length?{candidate:[...new Set(candidate)]}:{}),...(dir.length?{dir:[...new Set(dir)]}:{}),ext:['.java','.kt']};
}
function analyze(file,source){
  if(scan.tooLarge(source))return scan.EMPTY();
  const src=scan.prepare(source,DIALECT),{code}=src,imports=[];
  let pkg='',base;const root=()=>base===undefined?(base=scan.packageRoot(file,pkg,true)):base;
  const first=(a,b)=>{while(a<b&&scan.space(code[a]))a++;return a;};
  function decl(s,e){const h=scan.annotations(src,s,e,'at');const r=first(h.at,e),k=r+MODIFIERS.exec(code.slice(r,e))[0].length;return {start:first(s,e),k,list:h.list,text:code.slice(k,e)};}
  // `Map<String, List<X>> cache = ..., other;` -> cache, other (only the first declarator carries the type).
  function fields(text,at,owner,start,end){
    scan.splitTop(text).forEach((p,i)=>{
      const lhs=scan.blankAngles(p.text.split('=')[0]),m=/([A-Za-z_$][\w$]*)\s*(?:\[\s*\]\s*)*$/.exec(lhs);
      if(!m||i===0&&!/\S\s+$/.test(lhs.slice(0,m.index)))return;
      src.add('property',m[1],owner,{at:at+p.at+m.index,start,end});});
  }
  function components(at,o,owner){
    const p=code.indexOf('(',at);if(p<0||p>o||src.match[p]<p)return;
    for(const x of scan.splitTop(code.slice(p+1,src.match[p]))){const n=/([A-Za-z_$][\w$]*)\s*$/.exec(x.text);if(n)src.add('property',n[1],owner,{at:p+1+x.at+n.index,start:p+1+x.at,end:p+1+x.at+x.text.length});}
  }
  const typed=sig=>/[\w$\]]/.test(scan.blankAngles(sig.before));
  function body(from,to,ctx){
    let constants=ctx.kind==='enum';
    scan.walk(src,from,to,{
      brace:(s,o,c)=>{
        const d=decl(s,o);let m;
        if((m=/^(class|interface|enum|record|@\s*interface)\s+([A-Za-z_$][\w$]*)/.exec(d.text))){
          const kind=/interface/.test(m[1])?'interface':'class',name=m[2],at=d.k+m[0].length-name.length;
          src.add(kind,name,ctx.owner,{at,start:d.start,end:c+1});
          if(m[1]==='record')components(at,o,name);
          body(o+1,c,{owner:name,kind:m[1]==='enum'?'enum':kind,prefix:routePrefix(src,d.list)});constants=false;return true;
        }
        // Enum constants come first; one with a body (`A { ... },`) is not a member.
        if(constants)return true;
        const sig=scan.signature(src,d.k,o);
        if(sig&&!KEYWORDS.has(sig.name)&&!/=/.test(sig.before)&&/^\s*(?:throws\b[^]*)?$/.test(sig.after)&&(typed(sig)||sig.name===ctx.owner)){
          const r=ctx.owner?routeOf(src,d.list,ctx.prefix||''):null;
          src.add(r?'api.route':ctx.owner?'method':'function',r||sig.name,ctx.owner,{at:sig.at,start:d.start,end:c+1,span:true});return true;
        }
        // An initializer (`= {1, 2}`, `= new Foo() {...}`, a lambda) continues the field; anything else is a block.
        return !/=/.test(src.flat(d.k,o));
      },
      end:(s,e)=>{
        const d=decl(s,e),t=d.text.trim();let m;if(!t)return;
        if(constants){constants=false;return;}
        if((m=/^package\s+([\w.]+)/.exec(t))){pkg=m[1];return;}
        if((m=/^import\s+(static\s+)?([\w.]+?)(\s*\.\s*\*)?$/.exec(t))){imports.push(jvmImport(t.replace(/^import\s+/,'').replace(/\s+/g,' '),m[2],{wildcard:!!m[3],member:!!m[1],base:root()}));return;}
        if(!ctx.owner)return;
        const sig=scan.signature(src,d.k,e);
        if(sig&&!KEYWORDS.has(sig.name)&&!/=/.test(sig.before)){if(/^\s*(?:throws\b[^]*|default\b[^]*)?$/.test(sig.after)&&typed(sig))src.add('method',sig.name,ctx.owner,{at:sig.at,start:d.start,end:e});return;}
        if(/^(?:class|interface|enum|record)\b/.test(t))return;
        fields(d.text,d.k,ctx.owner,d.start,e);
      }});
  }
  body(0,code.length,{owner:'',kind:'top',prefix:''});
  return src.result(imports);
}
module.exports={id:'java',test:file=>/\.java$/i.test(file),analyze,routeOf,routePrefix,jvmImport};
