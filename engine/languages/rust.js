'use strict';
// Rust adapter: a dependency-free scanner over the shared lexer (engine/languages/scan.js), which knows raw strings
// (r#"..."#), byte and C strings, nested block comments and that 'a is a lifetime, not a char literal.
//
// Recognised: struct/enum/union (class) and named struct fields (property), traits (interface) with their methods,
// type aliases (type), functions, functions in `impl X` / `impl Trait for X` (method owned by X, generics, references
// and `dyn` stripped), associated consts (property), const/static items (variable), `macro_rules!` macros (function:
// a macro is a callable definition), inline `mod x { }` contents, and HTTP handlers with a literal path: actix/rocket
// attributes (`#[get("/x")]`, `#[route("/x", method = "GET")]`) and axum/actix `.route("/x", get(h).post(h2))`.
// Imports: `mod x;` resolves to x.rs or x/mod.rs beside the declaring file (Rust 2018: a non-mod.rs file declares its
// children in a folder named after it; `#[path = "..."]` is honoured); `use crate::a::b::C` / `self::` / `super::`
// resolve to the innermost module file that exists (a/b/C.rs, a/b.rs, a.rs, ... or the crate root); any other path is a
// candidate under the crate's src/ (2018 uniform paths) or a workspace crate named in a Cargo.toml.
// Not recognised: items generated by macros (derives, macro invocations), enum variants, tuple-struct fields and
// anything declared inside function bodies.
const path=require('node:path').posix;
const scan=require('./scan');
const DIALECT={rust:true,nest:true,chars:'rust',multiline:true};
const QUALIFIERS=/^(?:pub\s*(?:\([^)]*\))?\s*)?(?:(?:default|async|unsafe|safe|auto)\s+|const\s+(?=(?:async|unsafe|extern|fn)\b))*(?:extern\s*(?:"[^"]*"\s*)?(?=fn\b))?/;
const ROUTE_ATTR=/^(?:[\w:]+::)?(get|post|put|delete|patch|head|options|trace|connect|route)$/;
const EXTERNAL=new Set(['std','core','alloc','proc_macro','test']);
const ROOT=/^(?:lib|main|mod|build)\.rs$/;
// Where the child modules of this file live: beside a crate root or mod.rs, else in a folder named after the file.
function moduleDir(file){
  const dir=path.dirname(file),base=path.basename(file);
  const root=ROOT.test(base)||/(?:^|\/)(?:src\/bin|tests|examples|benches)$/.test(dir);
  const d=root?dir:path.join(dir,base.replace(/\.rs$/,''));return d==='.'?'':d;
}
function crateSrc(file){const parts=path.dirname(file).split('/');const k=parts.lastIndexOf('src');const d=k>=0?parts.slice(0,k+1).join('/'):path.dirname(file);return d==='.'?'':d;}
const join=(...p)=>p.filter(Boolean).join('/');
// Files that may define a path's item: a/b/C.rs, a/b/C/mod.rs, a/b.rs, a/b/mod.rs, a.rs, a/mod.rs.
function chain(base,rest){const out=[];for(let k=rest.length;k>=1;k--){const p=join(base,...rest.slice(0,k));out.push(p,p+'/mod');}return out;}
function moduleFile(dir,crate){return dir===crate?[join(dir,'lib'),join(dir,'main')]:dir?[dir,dir+'/mod']:[];}
function useTree(t,prefix,out){
  t=t.trim();if(!t)return;
  const b=t.indexOf('{');
  if(b<0){const segs=[...prefix,...t.split(/\s+as\s+/)[0].split('::').map(x=>x.trim()).filter(Boolean)];
    while(segs.length&&(segs.at(-1)==='self'||segs.at(-1)==='*'))segs.pop();if(segs.length)out.push(segs);return;}
  const base=[...prefix,...t.slice(0,b).split('::').map(x=>x.trim()).filter(Boolean)],inner=t.slice(b+1,t.lastIndexOf('}'));
  let depth=0,s=0;
  for(let i=0;i<=inner.length;i++){const c=inner[i];if(c==='{')depth++;else if(c==='}')depth--;else if((c===','||c===undefined)&&depth===0){
    const part=inner.slice(s,i).trim();if(part==='self'){if(base.length)out.push(base.slice());}else useTree(part,base,out);s=i+1;}}
}
function analyze(file,source){
  if(scan.tooLarge(source))return scan.EMPTY();
  const src=scan.prepare(source,DIALECT),{code,match}=src,imports=[];
  const own=file.replace(/\.rs$/,''),crate=crateSrc(file),mdir=moduleDir(file);
  const first=(a,b)=>{while(a<b&&scan.space(code[a]))a++;return a;};
  function decl(s,e){const h=scan.annotations(src,s,e,'hash');const r=first(h.at,e);const k=r+QUALIFIERS.exec(code.slice(r,e))[0].length;return {k,raw:code.slice(r,e),attrs:h.list,text:code.slice(k,e)};}
  function route(attrs){
    for(const a of attrs){
      const m=ROUTE_ATTR.exec(a.name);if(!m)continue;
      const p=code.indexOf('(',a.start);if(p<0||p>a.end)continue;
      const value=scan.pathArg(src,p,match[p],['path']);if(value===null)continue;
      let method=m[1].toUpperCase();
      if(method==='ROUTE'){const ms=[...code.slice(p,match[p]).matchAll(/\bmethod\s*=\s*"/g)].map(x=>src.stringAt(p+x.index+x[0].length-1));method=ms.length===1&&ms[0]?ms[0].toUpperCase():'ROUTE';}
      return scan.routeName(method,value);
    }
    return null;
  }
  function fields(open,close,owner){
    // Named fields: `pub name: Type,` at the body's top level (nested brackets and attributes blanked first).
    const body=code.slice(open+1,close).split('');
    for(let i=open+1;i<close;i++){const c=code[i];if((c==='('||c==='['||c==='{')&&match[i]>i){for(let k=i+1;k<match[i];k++)body[k-open-1]=' ';i=match[i];}}
    const found=[...body.join('').replace(/#\s*\[\s*\]/g,m=>' '.repeat(m.length)).matchAll(/(?:^|,)\s*(?:pub\s*(?:\(\s*[\w:\s]*\))?\s+)?((?:r#)?[A-Za-z_]\w*)\s*:(?!:)/g)];
    found.forEach((m,j)=>{const k=open+1+m.index+m[0].lastIndexOf(m[1]),e=j+1<found.length?open+1+found[j+1].index:close;
      src.add('property',m[1].replace(/^r#/,''),owner,{at:k,start:k,end:e});});
  }
  function implTarget(t){
    let s=t.replace(/^impl\s*/,'');
    if(s[0]==='<'){let depth=0,i=0;for(;i<s.length;i++){if(s[i]==='<')depth++;else if(s[i]==='>'&&s[i-1]!=='-'&&--depth===0)break;}s=s.slice(i+1);}
    const parts=s.split(/\bwhere\b/)[0].split(/\bfor\b/);
    const ty=parts.at(-1).trim().replace(/^(?:[!&\s]|'\w+\s*|mut\s+|dyn\s+)+/,'').split('<')[0];
    const m=/([A-Za-z_]\w*)\s*$/.exec(ty);return m?m[1]:'';
  }
  function modImport(name,attrs,modPath){
    const pa=attrs.find(a=>a.name==='path');
    if(pa){const v=src.stringsIn(pa.start,pa.end).map(x=>x[1]).find(x=>typeof x==='string');if(v){const t=path.normalize(path.join(path.dirname(file),v));if(!t.startsWith('../'))imports.push({spec:`mod ${name}`,target:t,ext:['']});return;}}
    const base=join(mdir,...modPath,name);imports.push({spec:`mod ${name}`,target:base,alt:base+'/mod',ext:['.rs']});
  }
  function uses(text,modPath){
    const leaves=[];useTree(text.replace(/^use\s+/,'').replace(/^::/,''),[],leaves);
    for(const segs of leaves){
      const spec=segs.join('::').slice(0,180);let base=null,rest=segs;
      if(segs[0]==='crate'){base=crate;rest=segs.slice(1);}
      else if(segs[0]==='self'||segs[0]==='super'){
        let dir=join(mdir,...modPath),k=0;if(segs[0]==='self')k=1;else while(segs[k]==='super'){dir=path.dirname(dir)==='.'?'':path.dirname(dir);k++;}
        base=dir;rest=segs.slice(k);
      }
      if(base!==null){
        // The module's own file ends the chain, unless it is this file (`use super::*` in an inline test module).
        const mod=moduleFile(base,crate);
        const files=[...chain(base,rest),...(mod.includes(own)?[]:mod)].filter((x,i,a)=>x!==own&&a.indexOf(x)===i);
        if(files.length)imports.push({spec,target:files[0],...(files.length>1?{alt:files.slice(1)}:{}),ext:['.rs']});
        continue;
      }
      if(EXTERNAL.has(segs[0])){imports.push({spec,target:null});continue;}
      const cands=chain(crate,segs).filter(x=>x!==own);
      imports.push({spec,target:null,...(cands.length?{candidate:cands}:{}),ext:['.rs'],manifest:'rust',pkg:segs.join('/')});
    }
  }
  function items(from,to,ctx){
    scan.walk(src,from,to,{
      brace:(s,o,c)=>{
        const d=decl(s,o);let m;
        if(/^use\s/.test(d.text))return false;
        if((m=/^fn\s+((?:r#)?[A-Za-z_]\w*)/.exec(d.text))){
          const r=route(d.attrs);const kind=r?'api.route':ctx.owner?'method':'function';
          src.add(kind,r||m[1],ctx.owner,{at:d.k,start:d.k,end:c+1,span:true});return true;}
        if((m=/^(?:struct|union)\s+([A-Za-z_]\w*)/.exec(d.text))){src.add('class',m[1],'',{at:d.k,start:d.k,end:c+1});fields(o,c,m[1]);return true;}
        if((m=/^enum\s+([A-Za-z_]\w*)/.exec(d.text))){src.add('class',m[1],'',{at:d.k,start:d.k,end:c+1});return true;}
        if((m=/^trait\s+([A-Za-z_]\w*)/.exec(d.text))){src.add('interface',m[1],'',{at:d.k,start:d.k,end:c+1});items(o+1,c,{owner:m[1],modPath:ctx.modPath});return true;}
        if(/^impl\b/.test(d.text)){const t=implTarget(d.text.trim());items(o+1,c,{owner:t,modPath:ctx.modPath});return true;}
        if((m=/^mod\s+([A-Za-z_]\w*)\s*$/.exec(d.text))){items(o+1,c,{owner:'',modPath:[...ctx.modPath,m[1]]});return true;}
        if((m=/^macro_rules\s*!\s*([A-Za-z_]\w*)/.exec(d.text))){src.add('function',m[1],ctx.owner,{at:d.k,start:d.k,end:c+1});return true;}
        if(/^(?:unsafe\s+)?extern\b(?:\s*"[^"]*")?\s*$/.test(d.raw)){items(o+1,c,ctx);return true;}
        // An initializer (`const X: T = T { .. };`) continues the statement; any other block ends it.
        return !/=/.test(d.text);
      },
      end:(s,e)=>{
        const d=decl(s,e);let m;const t=d.text.trim();if(!t)return;
        if(/^use\s/.test(t)){uses(t,ctx.modPath);return;}
        if((m=/^mod\s+([A-Za-z_]\w*)$/.exec(t))){modImport(m[1],d.attrs,ctx.modPath);return;}
        if((m=/^extern\s+crate\s+([A-Za-z_]\w*)/.exec(t))){imports.push({spec:m[1],target:null,manifest:'rust',pkg:m[1]});return;}
        if((m=/^fn\s+((?:r#)?[A-Za-z_]\w*)/.exec(t))){src.add(ctx.owner?'method':'function',m[1],ctx.owner,{at:d.k,start:d.k,end:e});return;}
        if((m=/^(?:struct|union)\s+([A-Za-z_]\w*)/.exec(t))){src.add('class',m[1],'',{at:d.k,start:d.k,end:e});return;}
        if((m=/^type\s+([A-Za-z_]\w*)/.exec(t))){if(!ctx.owner)src.add('type',m[1],'',{at:d.k,start:d.k,end:e});return;}
        if((m=/^(?:const|static)\s+(?:mut\s+)?([A-Za-z_]\w*)\s*:/.exec(t))&&m[1]!=='_')src.add(ctx.owner?'property':'variable',m[1],ctx.owner,{at:d.k,start:d.k,end:e});
      }});
  }
  items(0,code.length,{owner:'',modPath:[]});
  routes(src);
  return src.result(imports);
}
const METHODS=/(?:^|[^\w])(get|post|put|patch|delete|head|options|trace|any)\s*\(/g;
function routes(src){
  const {code,match}=src,re=/\.route\s*\(/g;let m;
  while((m=re.exec(code))){
    const open=m.index+m[0].length-1;const a=src.args(open);if(a.length<2)continue;
    const p=src.literalIn(a[0][0],a[0][1]);if(typeof p!=='string'||!p.startsWith('/'))continue;
    const methods=[...new Set([...code.slice(a[1][0],a[1][1]).matchAll(METHODS)].map(x=>x[1]==='any'?'ROUTE':x[1].toUpperCase()))];
    const owner=src.ownerAt(m.index),close=match[open];
    for(const method of methods.length?methods:['ROUTE'])src.add('api.route',scan.routeName(method,p),owner,{at:m.index,start:m.index,end:close+1});
  }
}
module.exports={id:'rust',test:file=>/\.rs$/i.test(file),analyze,moduleDir,crateSrc};
